"""Traceability gate (Day 5 L0: "mỗi commit có US/FR") + matrix check.

    python scripts/check_traceability.py commits <git range>   # e.g. origin/main..HEAD
    python scripts/check_traceability.py matrix                # docs/traceability.md is complete and points at real files
    python scripts/check_traceability.py message <file>        # one message — the commit-msg hook (.githooks/)

Commit rule: Conventional Commits subject (`type(scope)!: summary`) and at least one requirement code in the subject
or body — US-xxx (user story), EN-xx (enabler), REL-xx (release task) or BR-xxx (business requirement). Merge and
revert commits generated by git are exempt."""

from __future__ import annotations

import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CONVENTIONAL = re.compile(r"^(feat|fix|refactor|perf|test|docs|ci|build|chore|style|revert)(\([\w./-]+\))?!?: \S")
CODE = re.compile(r"\b(US-\d{3}|EN-\d{2}|REL-\d{2}|BR-\d{3})\b")
EXEMPT = re.compile(r"^(Merge |Revert \")")
STORY = re.compile(r"^### (US-\d{3})", re.M)
PATH_CELL = re.compile(r"`((?:backend|web|e2e|eval|infra|scripts)/[^`\s]+)`")


def check_message(message: str) -> list[str]:
    """Problems with one commit message (empty list = OK)."""
    subject = message.strip().splitlines()[0] if message.strip() else ""
    if EXEMPT.match(subject):
        return []
    problems = []
    if not CONVENTIONAL.match(subject):
        problems.append(f"not a Conventional Commit subject: {subject!r}")
    if not CODE.search(message):
        problems.append(f"no requirement code (US-xxx / EN-xx / REL-xx / BR-xxx): {subject!r}")
    return problems


def commits(rev_range: str) -> int:
    out = subprocess.run(
        ["git", "log", "--format=%H%x1f%B%x1e", rev_range], cwd=ROOT, capture_output=True, text=True, check=True
    ).stdout
    failures = 0
    for record in filter(str.strip, out.split("\x1e")):
        sha, _, body = record.strip().partition("\x1f")
        for p in check_message(body):
            failures += 1
            print(f"{sha[:8]}: {p}")
    print(f"traceability: {'FAIL' if failures else 'OK'} ({rev_range})")
    return 1 if failures else 0


def message_file(path: str) -> int:
    """commit-msg hook: the hard rule runs before the commit exists, not only in CI (Day 7: luật cứng → hook)."""
    with open(path, encoding="utf-8") as f:
        text = "\n".join(line for line in f.read().splitlines() if not line.startswith("#"))
    problems = check_message(text)
    for p in problems:
        print(f"commit-msg: {p}", file=sys.stderr)
    if problems:
        print("commit-msg: e.g. 'feat(qa): short summary [US-304]' — see AGENTS.md §8", file=sys.stderr)
    return 1 if problems else 0


def _read(path: str) -> str:
    with open(os.path.join(ROOT, path), encoding="utf-8") as f:
        return f.read()


def matrix_problems(stories_md: str, matrix_md: str, exists=os.path.exists, read=_read) -> list[str]:
    problems = [f"{us} is not in docs/traceability.md" for us in STORY.findall(stories_md) if us not in matrix_md]
    for path in sorted(set(PATH_CELL.findall(matrix_md))):
        file_part, _, test_name = path.partition("::")
        if not exists(os.path.join(ROOT, file_part)):
            problems.append(f"docs/traceability.md points at a missing file: {file_part}")
        elif test_name and not re.search(r"def " + re.escape(test_name) + "(?![A-Za-z0-9_])", read(file_part)):
            problems.append(f"docs/traceability.md points at a missing test: {path}")
    return problems


def matrix() -> int:
    with open(os.path.join(ROOT, "docs/implement/userStory.md"), encoding="utf-8") as f:
        stories = f.read()
    with open(os.path.join(ROOT, "docs/traceability.md"), encoding="utf-8") as f:
        mx = f.read()
    problems = matrix_problems(stories, mx)
    for p in problems:
        print(p)
    print(f"traceability matrix: {'FAIL' if problems else 'OK'}")
    return 1 if problems else 0


if __name__ == "__main__":
    if len(sys.argv) >= 2 and sys.argv[1] == "matrix":
        sys.exit(matrix())
    if len(sys.argv) == 3 and sys.argv[1] == "message":
        sys.exit(message_file(sys.argv[2]))
    if len(sys.argv) == 3 and sys.argv[1] == "commits":
        sys.exit(commits(sys.argv[2]))
    print(__doc__)
    sys.exit(2)
